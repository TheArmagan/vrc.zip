/**
 * What a saved node graph is, on the wire and in the `graphs.definition` blob.
 *
 * One definition, read by three things that must not drift: the editor that draws it, the daemon
 * that runs it, and the validator below that both of them call. That is the same argument
 * `NodeDefinition` makes in `@vrcz/plugin-api` — see PLAN.md §Node type registration — one level up.
 *
 * ## What is checked here, and what is not
 *
 * {@link validateGraphDocument} answers everything that can be decided from the document alone:
 * shape, duplicate ids, edges pointing at nodes that are not there, ports wired to themselves,
 * cycles, and the ceilings. It deliberately does **not** check port *types* or whether a node type
 * exists — both need the node registry, which lives in the daemon and is populated by running
 * plugins. That check is `checkEdge`, and it runs on save in the daemon and live in the editor.
 *
 * Both halves run twice on purpose, in the editor and again in the daemon, because the frontend is a
 * client and clients lie.
 *
 * ## Why this lives in `@vrcz/shared` rather than `@vrcz/plugin-api`
 *
 * A graph is not part of the plugin API: plugins contribute node *types*, they do not author or read
 * graphs (decision 206 keeps graphs first-party and session-token only). And the dependency runs one
 * way — `@vrcz/plugin-api` imports this package, so this package cannot import it back. The one cost
 * of that is {@link GraphNodeConfig}, which has to mirror `NodeConfigValues` structurally; the
 * daemon asserts the two agree at compile time, since it is the one place that imports both.
 */

/**
 * A node instance's configured values, keyed by field id.
 *
 * The wire mirror of `NodeConfigValues` from `@vrcz/plugin-api/nodes`, which cannot be imported here
 * without a cycle. `daemon/src/graphs/types.ts` holds an assignability check in both directions, so
 * a change to either one is a compile error rather than a shape that quietly disagrees.
 */
export type GraphNodeConfig = Readonly<Record<string, string | number | boolean>>;

/** Canvas coordinates. Editor-only: the runtime never reads these. */
export interface GraphNodePosition {
  readonly x: number;
  readonly y: number;
}

export interface GraphNode {
  /** Unique within the graph. Generated by the editor; an edge references this, never the type. */
  readonly id: string;
  /** The qualified node type: `<pluginId>/<nodeId>`, or the reserved namespace for a built-in. */
  readonly type: string;
  readonly position: GraphNodePosition;
  readonly config: GraphNodeConfig;
  /**
   * The `nodeDefinitionHash` of the definition this node was configured against.
   *
   * This is what makes an incompatible plugin update visible instead of silent. On load the daemon
   * compares it against the definition the plugin registers now; a mismatch **blocks the graph**
   * until the user migrates it in the editor, rather than rewiring a graph they already armed.
   * Absent for a node saved before its type was ever registered, which is not an error — a graph
   * referencing a stopped plugin is a normal state.
   */
  readonly defHash?: string;
  /**
   * Stop the run here, before this node executes, and wait for a person.
   *
   * Part of the document rather than a scribble the editor keeps to itself, for the same reason a
   * node's position is: it is something the author placed. A breakpoint that evaporated when the
   * tab closed would be useless for the case it exists for, which is a graph that misbehaves half
   * an hour later on a fire nobody was sitting there watching.
   *
   * **Honoured only while the graph is in debug mode.** A breakpoint forgotten in a saved graph
   * must not be able to park a run forever on a machine nobody is looking at, and tying it to the
   * switch the author flips when they sit down to debug is the smallest rule that guarantees it.
   */
  readonly breakpoint?: boolean;
}

/** One end of an edge: a node instance and one of its ports. */
export interface GraphEdgeEnd {
  readonly node: string;
  readonly port: string;
}

export interface GraphEdge {
  readonly id: string;
  readonly from: GraphEdgeEnd;
  readonly to: GraphEdgeEnd;
}

/** The whole document. Everything the editor saves and the runtime walks. */
export interface GraphDocument {
  readonly nodes: readonly GraphNode[];
  readonly edges: readonly GraphEdge[];
}

/**
 * What happens when a trigger fires while a run of the same graph is still in flight.
 *
 * The author's choice rather than one imposed default, because neither is right for everyone:
 * instance joins arrive in bursts, so serialising by fiat makes a graph lag the event stream, and
 * dropping by fiat loses events. Whatever the mode, a fire that is not honoured is **recorded** as
 * `graph.run.dropped` — an automation that silently skips is indistinguishable from a broken one.
 */
export const GRAPH_CONCURRENCY_MODES = ["parallel", "queue", "drop"] as const;

export type GraphConcurrency = (typeof GRAPH_CONCURRENCY_MODES)[number];

export function isGraphConcurrency(value: unknown): value is GraphConcurrency {
  return (
    typeof value === "string" && (GRAPH_CONCURRENCY_MODES as readonly string[]).includes(value)
  );
}

/**
 * The states a run can be in while it still exists.
 *
 * There is no `finished` or `failed`: a run that ended is deleted from `graph_runs` and its record
 * is an `events` row with a `graph.*` kind. See `012_graphs.sql`.
 */
export const GRAPH_RUN_STATUSES = ["queued", "running", "waiting"] as const;

export type GraphRunStatus = (typeof GRAPH_RUN_STATUSES)[number];

/** Ceilings on the document itself. The runtime's own ceilings are separate; see PLAN.md §Phase 4. */
export const MAX_GRAPH_NODES = 256;
export const MAX_GRAPH_EDGES = 512;
export const MAX_GRAPH_NAME = 120;
export const MAX_GRAPH_DESCRIPTION = 2000;

/** One graph as the control API reports it, without its document. */
export interface GraphSummary {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  /** The user wants this graph to run. Its triggers are armed. */
  readonly enabled: boolean;
  /** Dry-run has been lifted, so outbound actions really happen. Never implied by `enabled`. */
  readonly armed: boolean;
  /**
   * The author is debugging this graph.
   *
   * A third switch rather than a client-side preference, and it buys three things that only the
   * daemon can give: every run records a {@link GraphTrace}, a failure that `on error` swallowed is
   * said out loud instead of vanishing into a wire, and `breakpoint` nodes actually park the run.
   *
   * Per graph, because that is the unit somebody debugs. A daemon-wide switch would mean the one
   * graph you are looking at costs the same as the eleven you are not, and the traces are the
   * expensive half: they hold what every node produced, which is the whole point of them.
   */
  readonly debug: boolean;
  readonly concurrency: GraphConcurrency;
  /** The default acting account. Null once the account it named is removed. */
  readonly accountId: string | null;
  /** Why the daemon switched this graph off, when it was the daemon that did it. */
  readonly disabledReason: string | null;
  readonly nodeCount: number;
  /**
   * The type ids of this graph's triggers, in document order.
   *
   * Free here — the daemon already parses the document to count the nodes — and it is what lets the
   * list say *what a graph watches for* rather than only how big it is. Type ids rather than titles,
   * because a title belongs to whoever registered the node and the client has that catalogue
   * already; sending a resolved title would freeze it at the moment the row was read.
   */
  readonly triggerTypes: readonly string[];
  /** When a run of this graph last started, or null if one never has. */
  readonly lastRunAt: number | null;
  readonly createdAt: number;
  readonly updatedAt: number;
}

export interface Graph extends GraphSummary {
  readonly definition: GraphDocument;
  /**
   * Node ids whose type has changed since the graph was saved.
   *
   * Computed by comparing each node's stored `defHash` against the definition registered right now.
   * A node whose type is not registered at all is **not** here: that is "the plugin is stopped",
   * which is a different sentence and a different fix. Empty for a graph that has never been saved
   * against a registered type, since there is nothing to compare.
   */
  readonly staleNodes: readonly string[];
}

