/**
 * A validation failure, carrying the path to the thing that is wrong.
 *
 * Same contract as `validateNodeDefinition` and `validateUINode` in `@vrcz/plugin-api`: a result
 * rather than a throw, and every message names a path, because the only person who can fix this is
 * the one looking at the canvas.
 */
export interface GraphIssue {
  readonly path: string;
  readonly message: string;
}

export interface GraphValidation {
  readonly ok: boolean;
  readonly issues: readonly GraphIssue[];
}

const OK: GraphValidation = { ok: true, issues: [] };

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isConfigValue(value: unknown): value is string | number | boolean {
  return (
    typeof value === "string" ||
    typeof value === "boolean" ||
    (typeof value === "number" && Number.isFinite(value))
  );
}

/**
 * Checks everything decidable without the node registry, and returns every problem rather than the
 * first — a canvas that reports one broken edge per save is a canvas nobody finishes fixing.
 */
export function validateGraphDocument(value: unknown): GraphValidation {
  const issues: GraphIssue[] = [];
  if (!isRecord(value)) return { ok: false, issues: [{ path: "", message: "not an object" }] };

  const nodes = value.nodes;
  const edges = value.edges;
  if (!Array.isArray(nodes)) issues.push({ path: "nodes", message: "must be an array" });
  if (!Array.isArray(edges)) issues.push({ path: "edges", message: "must be an array" });
  if (issues.length > 0) return { ok: false, issues };

  const nodeList = nodes as unknown[];
  const edgeList = edges as unknown[];
  if (nodeList.length > MAX_GRAPH_NODES) {
    issues.push({ path: "nodes", message: `more than ${MAX_GRAPH_NODES} nodes` });
  }
  if (edgeList.length > MAX_GRAPH_EDGES) {
    issues.push({ path: "edges", message: `more than ${MAX_GRAPH_EDGES} edges` });
  }

  const ids = new Set<string>();
  nodeList.forEach((node, i) => {
    const path = `nodes[${i}]`;
    if (!isRecord(node)) {
      issues.push({ path, message: "not an object" });
      return;
    }
    const id = node.id;
    if (typeof id !== "string" || id === "") {
      issues.push({ path: `${path}.id`, message: "must be a non-empty string" });
    } else if (ids.has(id)) {
      issues.push({ path: `${path}.id`, message: `duplicate node id "${id}"` });
    } else {
      ids.add(id);
    }
    if (typeof node.type !== "string" || node.type === "") {
      issues.push({ path: `${path}.type`, message: "must be a non-empty node type id" });
    }
    const position = node.position;
    if (
      !isRecord(position) ||
      typeof position.x !== "number" ||
      typeof position.y !== "number" ||
      !Number.isFinite(position.x) ||
      !Number.isFinite(position.y)
    ) {
      issues.push({ path: `${path}.position`, message: "must be finite {x, y}" });
    }
    const config = node.config;
    if (!isRecord(config)) {
      issues.push({ path: `${path}.config`, message: "must be an object" });
    } else {
      for (const [key, entry] of Object.entries(config)) {
        if (!isConfigValue(entry)) {
          issues.push({
            path: `${path}.config.${key}`,
            message: "must be a string, a finite number, or a boolean",
          });
        }
      }
    }
    if (node.defHash !== undefined && typeof node.defHash !== "string") {
      issues.push({ path: `${path}.defHash`, message: "must be a string when present" });
    }
    if (node.breakpoint !== undefined && typeof node.breakpoint !== "boolean") {
      issues.push({ path: `${path}.breakpoint`, message: "must be a boolean when present" });
    }
  });

  const edgeIds = new Set<string>();
  const wiredInputs = new Set<string>();
  const adjacency = new Map<string, string[]>();
  edgeList.forEach((edge, i) => {
    const path = `edges[${i}]`;
    if (!isRecord(edge)) {
      issues.push({ path, message: "not an object" });
      return;
    }
    const id = edge.id;
    if (typeof id !== "string" || id === "") {
      issues.push({ path: `${path}.id`, message: "must be a non-empty string" });
    } else if (edgeIds.has(id)) {
      issues.push({ path: `${path}.id`, message: `duplicate edge id "${id}"` });
    } else {
      edgeIds.add(id);
    }

    const resolveEnd = (side: "from" | "to", end: unknown): GraphEdgeEnd | null => {
      if (!isRecord(end) || typeof end.node !== "string" || typeof end.port !== "string") {
        issues.push({ path: `${path}.${side}`, message: "must be {node, port}" });
        return null;
      }
      if (!ids.has(end.node)) {
        issues.push({ path: `${path}.${side}.node`, message: `no node "${end.node}"` });
        return null;
      }
      return { node: end.node, port: end.port };
    };

    // Both sides are resolved before the early return, so a broken edge reports both ends rather
    // than sending the user back for a second save to hear about the other one.
    const from = resolveEnd("from", edge.from);
    const to = resolveEnd("to", edge.to);
    if (from === null || to === null) return;
    if (from.node === to.node) {
      issues.push({ path, message: "a node cannot be wired to itself" });
      return;
    }
    // One edge per input port. Two producers for one input has no defined merge, and a graph that
    // picks whichever arrived last is a graph that behaves differently on a busy evening.
    const inputKey = `${to.node}.${to.port}`;
    if (wiredInputs.has(inputKey)) {
      issues.push({ path: `${path}.to`, message: `input "${inputKey}" already has an edge` });
    } else {
      wiredInputs.add(inputKey);
    }
    const out = adjacency.get(from.node);
    if (out === undefined) adjacency.set(from.node, [to.node]);
    else out.push(to.node);
  });

  const cycle = findCycle(ids, adjacency);
  if (cycle !== null) {
    issues.push({ path: "edges", message: `cycle: ${cycle.join(" -> ")}` });
  }

  return issues.length === 0 ? OK : { ok: false, issues };
}

/**
 * The first cycle reachable in the graph, as the path that closes it, or null.
 *
 * Iterative rather than recursive: the depth is bounded by {@link MAX_GRAPH_NODES}, but this runs on
 * a document that arrived over HTTP, and a validator that can blow the stack on hostile input is a
 * denial of service in the shape of a helper.
 */
function findCycle(
  ids: ReadonlySet<string>,
  adjacency: ReadonlyMap<string, string[]>,
): string[] | null {
  const WHITE = 0;
  const GREY = 1;
  const BLACK = 2;
  const colour = new Map<string, number>();
  for (const id of ids) colour.set(id, WHITE);

  for (const root of ids) {
    if (colour.get(root) !== WHITE) continue;
    // Each frame is a node plus how far through its successors we are.
    const stack: { node: string; next: number }[] = [{ node: root, next: 0 }];
    colour.set(root, GREY);
    while (stack.length > 0) {
      const frame = stack[stack.length - 1];
      if (frame === undefined) break;
      const successors = adjacency.get(frame.node) ?? [];
      if (frame.next >= successors.length) {
        colour.set(frame.node, BLACK);
        stack.pop();
        continue;
      }
      const next = successors[frame.next];
      frame.next += 1;
      if (next === undefined) continue;
      const state = colour.get(next);
      if (state === GREY) {
        const start = stack.findIndex((f) => f.node === next);
        const path = stack.slice(start === -1 ? 0 : start).map((f) => f.node);
        path.push(next);
        return path;
      }
      if (state === WHITE) {
        colour.set(next, GREY);
        stack.push({ node: next, next: 0 });
      }
    }
  }
  return null;
}

/** Every node with no incoming edge — the roots a run can start from. */
export function graphRoots(document: GraphDocument): string[] {
  const targets = new Set(document.edges.map((edge) => edge.to.node));
  return document.nodes.filter((node) => !targets.has(node.id)).map((node) => node.id);
}

/**
 * The nodes reachable from `start`, including it.
 *
 * A run walks only what its own trigger reaches, which is what lets one graph hold several trigger
 * roots without a fire running branches that have no inputs.
 */
export function reachableFrom(document: GraphDocument, start: string): Set<string> {
  const out = new Map<string, string[]>();
  for (const edge of document.edges) {
    const list = out.get(edge.from.node);
    if (list === undefined) out.set(edge.from.node, [edge.to.node]);
    else list.push(edge.to.node);
  }
  const seen = new Set<string>();
  const queue = [start];
  while (queue.length > 0) {
    const node = queue.pop();
    if (node === undefined || seen.has(node)) continue;
    seen.add(node);
    for (const next of out.get(node) ?? []) if (!seen.has(next)) queue.push(next);
  }
  return seen;
}

/**
 * The `foreach` output ports that lead **into** the body, and the ones that lead **past** it.
 *
 * Named here rather than in the daemon's intrinsics because the canvas has to draw the same
 * boundary the engine walks. Two copies of this split is two answers to "is this node in the loop",
 * and the one on screen would be the one nobody tested.
 */
export const FOREACH_BODY_PORTS: readonly string[] = ["item", "index"];
export const FOREACH_AFTER_PORTS: readonly string[] = ["done", "results"];

/**
 * Which nodes belong to each loop's body.
 *
 * The body is what `item` and `index` reach, minus what `done` and `results` reach. That
 * subtraction is what lets one node sit after the loop *and* read the body — it is excluded from
 * the body, runs once in the outer scope, and sees the last iteration. Anything else would need a
 * second kind of edge to say "this one is after the loop", which is a concept the canvas does not
 * have and would have to explain.
 *
 * `loopIds` rather than a type check, because the type id lives in the daemon's reserved namespace
 * and this module is a leaf that may not import it.
 */
export function foreachBodies(
  document: GraphDocument,
  loopIds: Iterable<string>,
): Map<string, Set<string>> {
  const bodies = new Map<string, Set<string>>();
  for (const id of loopIds) {
    const after = reachableFromPorts(document, id, FOREACH_AFTER_PORTS);
    const body = reachableFromPorts(document, id, FOREACH_BODY_PORTS);
    for (const node of after) body.delete(node);
    body.delete(id);
    bodies.set(id, body);
  }
  return bodies;
}

/** Everything downstream of one node's named output ports, excluding the node itself. */
function reachableFromPorts(
  document: GraphDocument,
  nodeId: string,
  ports: readonly string[],
): Set<string> {
  const out = new Set<string>();
  for (const edge of document.edges) {
    if (edge.from.node !== nodeId || !ports.includes(edge.from.port)) continue;
    for (const id of reachableFrom(document, edge.to.node)) out.add(id);
  }
  out.delete(nodeId);
  return out;
}

/**
 * The loop a node belongs to, when loops are nested.
 *
 * The innermost one, always — the same scoping every language gives a `break`, so a `Collect` drawn
 * inside two loops appends to the one it is drawn in. The rule is structural rather than a size
 * comparison: a candidate is innermost when no other candidate loop node sits inside its body.
 * Returns null for a node that is in no body at all.
 */
export function innermostLoop(
  bodies: ReadonlyMap<string, ReadonlySet<string>>,
  nodeId: string,
): string | null {
  const candidates = [...bodies.entries()].filter(([, body]) => body.has(nodeId)).map(([id]) => id);
  for (const id of candidates) {
    const body = bodies.get(id);
    if (body === undefined) continue;
    if (!candidates.some((other) => other !== id && body.has(other))) return id;
  }
  return candidates[0] ?? null;
}
